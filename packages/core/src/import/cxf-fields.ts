/**
 * The credentials of a Credential Exchange Format item (CXF v1.0 §3.3) as Kennwort fields. Most
 * values are `EditableField`s (`fieldType`, `value`, `label`); a few are plain strings. Each kind
 * of credential fills the template fields of its entry type; a kind Kennwort has no type for
 * (driver's licence, passport, identity document, kinds of later versions) keeps every value as an
 * own field under its label or member name. Passkeys, TOTP and notes are read in cxf-json.ts,
 * files and item references stay out. Source: bitwarden/credential-exchange,
 * credential-exchange-format/src (login.rs, identity.rs, document.rs, editable_field.rs).
 */
import { z } from "zod";
import type { EntryContent, Field } from "../sync/content.ts";
import { pemOf } from "./cxf-passkey.ts";
import { custom, type DraftField, joinFilled, joinLines, known, type TemplateId } from "./entry.ts";
import { text } from "./schema.ts";

type EntryType = EntryContent["type"];
/** A credential as the file has it: its members by name */
export type Credential = Record<string, unknown>;

const EditableField = z.object({ fieldType: text, value: text, label: text });
type EditableField = z.infer<typeof EditableField>;

/** A member as an editable field; a plain string is a field without type and label */
const fieldOf = (value: unknown): EditableField | undefined =>
  typeof value === "string"
    ? { fieldType: "", value, label: "" }
    : EditableField.safeParse(value).data;

/** The value of a member, empty when it is missing or no field */
export const memberValue = (credential: Credential, member: string): string =>
  fieldOf(credential[member])?.value ?? "";

const KINDS = new Map<string, Field["kind"]>([
  ["concealed-string", "secret"],
  ["email", "email"],
]);

/** An own field from an editable field, named by its label or else the given name */
const ownField = (field: EditableField, name: string): DraftField =>
  custom(field.label || name, field.value, KINDS.get(field.fieldType) ?? "text");

/** CXF writes a card's expiry as YYYY-MM; Kennwort shows MM/YYYY */
const cardExpiry = (value: string) => value.replace(/^(\d{4})-(\d{2})$/, "$2/$1");

type Mapper = { type: EntryType; fields: (read: (member: string) => string) => DraftField[] };

const template = (id: TemplateId, value: string) => known(id, value);

const MAPPERS = new Map<string, Mapper>(
  Object.entries({
    "basic-auth": {
      type: "login",
      fields: (read) => [
        template("username", read("username")),
        template("password", read("password")),
      ],
    },
    "credit-card": {
      type: "card",
      fields: (read) => [
        template("holder", read("fullName")),
        template("number", read("number")),
        template("expiry", cardExpiry(read("expiryDate"))),
        template("cvc", read("verificationNumber")),
        template("pin", read("pin")),
        custom("Card type", read("cardType")),
        custom("Valid from", cardExpiry(read("validFrom"))),
      ],
    },
    wifi: {
      type: "wifi",
      fields: (read) => [
        template("ssid", read("ssid")),
        template("password", read("passphrase")),
        template("security", read("networkSecurityType")),
        custom("Hidden", read("hidden")),
      ],
    },
    "ssh-key": {
      type: "ssh-key",
      fields: (read) => [
        template("private-key", pemOf(read("privateKey"))),
        custom("Key type", read("keyType")),
        custom("Comment", read("keyComment")),
        custom("Created", read("creationDate")),
        custom("Expiry date", read("expiryDate")),
        custom("Generated by", read("keyGenerationSource")),
      ],
    },
    "api-key": {
      type: "api-key",
      fields: (read) => [
        template("key", read("key")),
        template("website", read("url")),
        template("username", read("username")),
        custom("Key type", read("keyType")),
        custom("Valid from", read("validFrom")),
        custom("Expiry date", read("expiryDate")),
      ],
    },
    address: {
      type: "identity",
      fields: (read) => [
        template(
          "address",
          joinLines(
            read("streetAddress"),
            joinFilled(" ", [read("postalCode"), read("city")]),
            read("territory"),
            read("country"),
          ),
        ),
        template("phone", read("tel")),
      ],
    },
    "person-name": {
      type: "identity",
      fields: (read) => [
        template(
          "name",
          joinFilled(
            " ",
            ["title", "given", "given2", "surnamePrefix", "surname", "surname2", "generation"].map(
              read,
            ),
          ),
        ),
        custom("Nickname", read("givenInformal")),
        custom("Credentials", read("credentials")),
      ],
    },
    "generated-password": {
      type: "login",
      fields: (read) => [custom("Generated password", read("password"), "secret")],
    },
  } satisfies Record<string, Mapper>),
);

/** Kinds read elsewhere or left out, and members that are no values */
const ELSEWHERE = new Set(["passkey", "totp", "note", "file", "item-reference"]);
/** The entry types of kinds without a mapper: documents of no known kind are identities */
const TYPES = new Map<string, EntryType>([
  ["totp", "login"],
  ["drivers-license", "identity"],
  ["passport", "identity"],
  ["identity-document", "identity"],
]);
const NOT_VALUES = new Set(["type", "id", "extensions"]);

/** Every value of a kind Kennwort has no type for, as own fields */
const anyFields = (credential: Credential): DraftField[] =>
  Object.entries(credential).flatMap(([member, value]) => {
    const field = NOT_VALUES.has(member) ? undefined : fieldOf(value);
    return field ? [ownField(field, member)] : [];
  });

/** A `custom-fields` credential: each field under its own label */
const customFields = (credential: Credential): DraftField[] => {
  const fields = Array.isArray(credential.fields) ? credential.fields : [];
  return fields.flatMap((value) => {
    const field = EditableField.safeParse(value).data;
    return field ? [ownField(field, "Field")] : [];
  });
};

/** The fields of one credential */
export const credentialFields = (credential: Credential): DraftField[] => {
  const kind = String(credential.type);
  const mapper = MAPPERS.get(kind);
  if (mapper) return mapper.fields((member) => memberValue(credential, member));
  if (kind === "custom-fields") return customFields(credential);
  return ELSEWHERE.has(kind) ? [] : anyFields(credential);
};

/** The entry type of the first credential that has one */
export const entryTypeOf = (credentials: Credential[]): EntryType | undefined =>
  credentials
    .map(({ type }) => MAPPERS.get(String(type))?.type ?? TYPES.get(String(type)))
    .find((type) => type !== undefined);
