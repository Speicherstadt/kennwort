/**
 * The migrations of drizzle/, as one TypeScript module: `bun build --compile` takes no folder along,
 * so the binary carries its migrations in its code (src/db/migrations.gen.ts).
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

export type EmbeddedMigration = { tag: string; when: number; breakpoints: boolean; sql: string };
type Journal = { entries: { tag: string; when: number; breakpoints: boolean }[] };

export const readMigrations = (folder: string): EmbeddedMigration[] => {
  const journal = JSON.parse(readFileSync(join(folder, "meta/_journal.json"), "utf8")) as Journal;
  return journal.entries.map(({ tag, when, breakpoints }) => ({
    tag,
    when,
    breakpoints,
    sql: readFileSync(join(folder, `${tag}.sql`), "utf8"),
  }));
};

export const migrationsModule = (migrations: EmbeddedMigration[]) =>
  [
    "// Generated by scripts/embed-migrations.ts from drizzle/; do not edit",
    'import type { EmbeddedMigration } from "./embed.ts";',
    "",
    `export const migrations: EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};`,
    "",
  ].join("\n");
